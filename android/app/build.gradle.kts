// ── Hosts ────────────────────────────────────────────────────────────────────────────────
// The public host lives in ONE place in android/: here. (Web: src/lib/site.ts · iOS: project.yml.)
val kuraPublicHost = "get-kura.app"
// Debug: the Mac's dev server seen from the emulator (10.0.2.2 = host loopback), started with
// `pnpm dev --port 3010`. `-PkuraApiHost=192.168.1.20:3010` points a debug build at the Mac by IP
// (physical phone on the same wifi). Always http: debug only, cleartext allowed for that host alone.
val kuraDebugApiHost: String = providers.gradleProperty("kuraApiHost").orNull
    ?.takeIf { it.isNotBlank() } ?: "10.0.2.2:3010"


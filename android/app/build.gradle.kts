// Debug network security config: cleartext ONLY for the dev hosts (emulator loopback, localhost
// and whatever -PkuraApiHost names). Generated per build so a phone pointed at the Mac's IP works
// without widening cleartext to every host. Release uses src/main/res/xml/network_security_config.xml
// (no cleartext at all).
abstract class DebugNetworkSecurityConfigTask : DefaultTask() {
    @get:Input abstract val hosts: SetProperty<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun write() {
        val domains = hosts.get().sorted().joinToString("\n") {
            "        <domain includeSubdomains=\"false\">$it</domain>"
        }
        val file = outputDir.get().file("xml/network_security_config_debug.xml").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- GENERATED by :app:generateDebugNetworkSecurityConfig — edit app/build.gradle.kts, not this file. -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false" />
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |    </domain-config>
            |</network-security-config>
            |""".trimMargin(),
        )
    }
}

val generateDebugNetworkSecurityConfig = tasks.register<DebugNetworkSecurityConfigTask>("generateDebugNetworkSecurityConfig") {
    hosts.set(setOf("10.0.2.2", "localhost", "127.0.0.1", kuraDebugApiHost.substringBefore(':')))
    outputDir.set(layout.buildDirectory.dir("generated/kura/debugNetworkSecurityConfig"))
}

androidComponents {
    onVariants(selector().withBuildType("debug")) { variant ->
        variant.sources.res?.addGeneratedSourceDirectory(
            generateDebugNetworkSecurityConfig,
            DebugNetworkSecurityConfigTask::outputDir,
        )
    }
}

